export function getAvailablePrizes(prizes = DEFAULT_PRIZES) {
  // Only return prizes that are enabled (stock > 0 and weight > 0)
  // Loss items ("Better Luck Next Time") have weight=0, ensuring NO student loses.
  return prizes.filter(p => !p.isLoss && p.weight > 0 && (p.stock === undefined || p.stock > 0));
}

export function pickWinningPrize(prizes = DEFAULT_PRIZES) {
  const available = getAvailablePrizes(prizes);
  if (available.length === 0) {
    // Fallback: pick any prize with weight > 0
    const fallback = prizes.filter(p => !p.isLoss && p.weight > 0);
    return fallback[Math.floor(Math.random() * fallback.length)] || prizes[0];
  }

  const totalWeight = available.reduce((acc, p) => acc + (p.weight || 1), 0);
  let random = Math.random() * totalWeight;

  for (const prize of available) {
    random -= (prize.weight || 1);
    if (random <= 0) {
      return prize;
    }
  }

  return available[0];
}

export function generateVoucherCode(prize) {
  if (prize.voucherCode) {
    return prize.voucherCode;
  }
  const prefix = prize.voucherPrefix || 'DIDAC';
  const chars = '23456789ABCDEFGHJKLMNPQRSTUVWXYZ';
  let rand = '';
  for (let i = 0; i < 4; i++) {
    rand += chars.charAt(Math.floor(Math.random() * chars.length));
  }
  return `${prefix}-${rand}`;
}
